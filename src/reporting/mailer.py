import os
import smtplib
from email.message import EmailMessage
import csv
import datetime

# Load local .env if it exists
env_path = os.path.join(os.path.dirname(__file__), '..', '..', '.env')
if os.path.exists(env_path):
    with open(env_path, 'r') as f:
        for line in f:
            if '=' in line and not line.strip().startswith('#'):
                k, v = line.strip().split('=', 1)
                os.environ[k] = v

HISTORY_FILE = "mini_soc_siem_alert_history.csv"

# Resolve path gracefully regardless of where the script is executed
EMAILS_FILE = "emails.csv"
if not os.path.exists(EMAILS_FILE) and os.path.exists("backend/emails.csv"):
    EMAILS_FILE = "backend/emails.csv"

def log_history(name, recipient, subject, status, report_file):
    now = datetime.datetime.now()
    date_str = now.strftime("%Y-%m-%d")
    time_str = now.strftime("%H:%M:%S")
    
    write_header = not os.path.exists(HISTORY_FILE) or os.stat(HISTORY_FILE).st_size == 0
    
    with open(HISTORY_FILE, mode='a', newline='', encoding='utf-8') as f:
        writer = csv.writer(f)
        if write_header:
            writer.writerow(["Date", "Time", "Name", "Recipient", "Subject", "Status", "Report_File"])
        writer.writerow([date_str, time_str, name, recipient, subject, status, report_file])

def send_alerts_to_list(attachment_path: str):
    subject = "Daily Security Operations Report (Mini SOC SIEM)"
    body = "Hello Team,\n\nPlease find attached the latest Security Operations Center (SOC) incident report generated by the SIEM platform.\n\nThis is an automated system notification containing your requested summary.\n\nBest regards,\nSecurity Operations Team"
    
    smtp_host = os.getenv("SMTP_HOST", "smtp.gmail.com")
    smtp_port = int(os.getenv("SMTP_PORT", "587"))
    smtp_user = os.getenv("SMTP_USER", "your_email@gmail.com")
    smtp_pass = os.getenv("SMTP_PASS", "your_app_password")
    from_email = os.getenv("FROM_EMAIL", smtp_user)
    
    recipients = []
    if os.path.exists(EMAILS_FILE):
        with open(EMAILS_FILE, mode='r', encoding='utf-8') as f:
            reader = csv.DictReader(f)
            for row in reader:
                if row.get("Email"):
                    recipients.append({"name": row.get("Name", "Unknown"), "email": row["Email"]})
                    
    if not recipients:
        print("No recipients found in emails.csv. Cannot send alerts.")
        return

    report_filename = os.path.basename(attachment_path)

    if not smtp_user or not smtp_pass:
        print("SMTP credentials not found. MOCKING email send.")
        for r in recipients:
            print(f"MOCK SEND to {r['email']}")
            log_history(r['name'], r['email'], subject, "Mock Sent", report_filename)
        return

    try:
        with open(attachment_path, "rb") as f:
            pdf_data = f.read()

        with smtplib.SMTP(smtp_host, smtp_port) as server:
            server.starttls()
            server.login(smtp_user, smtp_pass)
            
            for r in recipients:
                msg = EmailMessage()
                msg["From"] = from_email
                msg["To"] = r['email']
                msg["Subject"] = subject
                msg.set_content(body)
                msg.add_attachment(pdf_data, maintype="application", subtype="pdf", filename=report_filename)
                
                try:
                    server.send_message(msg)
                    print(f"Sent email to {r['email']}")
                    log_history(r['name'], r['email'], subject, "Sent", report_filename)
                except Exception as e:
                    print(f"Failed to send email to {r['email']}: {str(e)}")
                    log_history(r['name'], r['email'], subject, f"Failed: {str(e)}", report_filename)
    except Exception as e:
        print(f"Failed to connect to SMTP: {str(e)}")
        for r in recipients:
            log_history(r['name'], r['email'], subject, "Failed Connection", report_filename)